"""Train four TabPFN CPU regressors and export joblib models for the server.

Input:
  training.csv with the same columns generated by:
    python tabpfn_service.py --write-training-template training_template.csv

Output:
  models/fl_x.joblib
  models/fl_y.joblib
  models/fd_x.joblib
  models/fd_y.joblib
  models/model_manifest.json

Each exported joblib object is a complete sklearn Pipeline:
  SimpleImputer -> MinMaxScaler -> TabPFNRegressor

The server can load these files directly with TRIFOCUS_MODEL_MODE=joblib.
"""

from __future__ import annotations

import argparse
import json
import os
from datetime import datetime, timezone
from pathlib import Path

os.environ.setdefault("DO_NOT_TRACK", "1")
os.environ.setdefault("POSTHOG_DISABLED", "1")
os.environ.setdefault("OMP_NUM_THREADS", "2")

import numpy as np
import pandas as pd

from tabpfn_service import FEATURE_COLUMNS, TARGET_COLUMNS


def build_regressor(n_estimators: int, random_state: int, model_path: Path):
    from tabpfn import TabPFNRegressor

    return TabPFNRegressor(
        device="cpu",
        n_estimators=n_estimators,
        model_path=model_path,
        ignore_pretraining_limits=True,
        random_state=random_state,
        show_progress_bar=False,
    )


def fit_preprocessor(x: pd.DataFrame) -> dict[str, list[float]]:
    values = x.to_numpy(dtype=float)
    medians = np.nanmedian(values, axis=0)
    medians = np.where(np.isfinite(medians), medians, 0.0)
    filled = np.where(np.isfinite(values), values, medians)
    min_values = filled.min(axis=0)
    max_values = filled.max(axis=0)
    span = np.where(max_values > min_values, max_values - min_values, 1.0)
    return {
        "medians": medians.tolist(),
        "min_values": min_values.tolist(),
        "span": span.tolist(),
    }


def transform_features(x: pd.DataFrame, preprocessor: dict[str, list[float]]) -> np.ndarray:
    values = x.to_numpy(dtype=float)
    medians = np.asarray(preprocessor["medians"], dtype=float)
    min_values = np.asarray(preprocessor["min_values"], dtype=float)
    span = np.asarray(preprocessor["span"], dtype=float)
    filled = np.where(np.isfinite(values), values, medians)
    return (filled - min_values) / span


def load_training_data(path: Path, max_rows: int | None) -> pd.DataFrame:
    df = pd.read_csv(path)
    required = FEATURE_COLUMNS + list(TARGET_COLUMNS.values())
    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"Training CSV missing columns: {missing}")

    numeric = df[required].apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan)
    numeric = numeric.dropna(subset=list(TARGET_COLUMNS.values())).reset_index(drop=True)
    if max_rows is not None and len(numeric) > max_rows:
        numeric = numeric.sample(n=max_rows, random_state=42).reset_index(drop=True)
    if len(numeric) < 20:
        raise ValueError(f"Too few usable training rows: {len(numeric)}")
    return numeric


def train_and_export(
    training_csv: Path,
    output_dir: Path,
    *,
    model_path: Path,
    n_estimators: int,
    max_rows: int | None,
) -> dict[str, object]:
    if not model_path.exists():
        raise FileNotFoundError(f"TabPFN model checkpoint not found: {model_path}")
    output_dir.mkdir(parents=True, exist_ok=True)
    df = load_training_data(training_csv, max_rows)
    x = df[FEATURE_COLUMNS]
    preprocessor = fit_preprocessor(x)
    x_scaled = transform_features(x, preprocessor)

    outputs: dict[str, str] = {}
    for index, (target_key, target_column) in enumerate(TARGET_COLUMNS.items()):
        print(f"[train] {target_key} <= {target_column} rows={len(df)}", flush=True)
        y = df[target_column].to_numpy(dtype=float)
        if np.nanmax(y) == np.nanmin(y):
            bundle = {
                "kind": "constant",
                "value": float(y[0]),
                "feature_columns": FEATURE_COLUMNS,
                "target_column": target_column,
            }
        else:
            model = build_regressor(n_estimators=n_estimators, random_state=42 + index, model_path=model_path)
            model.fit(x_scaled, y)
            bundle = {
                "kind": "tabpfn_regressor_bundle",
                "feature_columns": FEATURE_COLUMNS,
                "target_column": target_column,
                "preprocessor": preprocessor,
                "model": model,
            }
        out_path = output_dir / f"{target_key}.joblib"
        import joblib

        joblib.dump(bundle, out_path, compress=3)
        outputs[target_key] = out_path.as_posix()
        print(f"[saved] {out_path}", flush=True)

    manifest = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "training_csv": training_csv.as_posix(),
        "training_rows": int(len(df)),
        "feature_columns": FEATURE_COLUMNS,
        "target_columns": TARGET_COLUMNS,
        "n_estimators": n_estimators,
        "max_rows": max_rows,
        "model_path": model_path.as_posix(),
        "outputs": outputs,
    }
    manifest_path = output_dir / "model_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Train and export TriFocus TabPFN joblib models.")
    parser.add_argument("--training-csv", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("models/tabpfn_server"))
    parser.add_argument("--model-path", type=Path, default=Path("models/offline_tabpfn_2_5/tabpfn-v2.5-regressor-v2.5_default.ckpt"))
    parser.add_argument("--n-estimators", type=int, default=1)
    parser.add_argument("--max-rows", type=int, default=2000)
    args = parser.parse_args()

    manifest = train_and_export(
        args.training_csv,
        args.output_dir,
        model_path=args.model_path,
        n_estimators=args.n_estimators,
        max_rows=args.max_rows,
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
